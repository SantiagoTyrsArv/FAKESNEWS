// Tailwind CSS 4 at-rules that stylelint-config-standard does not know about.
const tailwindAtRules = [
  "theme",
  "custom-variant",
  "apply",
  "utility",
  "variant",
  "source",
  "reference",
  "plugin",
  "config",
];

const config = {
  extends: ["stylelint-config-standard"],
  rules: {
    // Tailwind directives are valid at-rules that Stylelint does not recognize.
    "at-rule-no-unknown": [true, { ignoreAtRules: tailwindAtRules }],
    // Same directives, checked by the deprecation rule in Stylelint 17.
    "at-rule-no-deprecated": [true, { ignoreAtRules: tailwindAtRules }],
    // @apply takes Tailwind utility names, not valid CSS preludes.
    "at-rule-prelude-no-invalid": [true, { ignoreAtRules: ["apply"] }],
    // Tailwind and Next resolve bare-string @import specifiers; url("tailwindcss") would not.
    "import-notation": "string",
    // oklch() tokens use the decimal/unitless form generated by shadcn/Tailwind;
    // converting to percentages/deg would churn every color for no rendering change.
    "lightness-notation": null,
    "hue-degree-notation": null,
    // -webkit-box-decoration-break is still needed for Safari/older Chromium (no autoprefixer here).
    "property-no-vendor-prefix": [true, { ignoreProperties: ["-webkit-box-decoration-break"] }],
  },
};

export default config;
